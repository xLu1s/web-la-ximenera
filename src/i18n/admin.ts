export type AdminKey = keyof typeof M;

export function ta(lang: AdminLang, key: AdminKey, vars?: Record<string, string | number>): string {
  let s: string = M[key][lang];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

