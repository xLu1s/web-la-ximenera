export type PublicKey = keyof typeof M;

export function t(lang: PublicLang, key: PublicKey, vars?: Record<string, string | number>): string {
  let s: string = M[key][lang];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

const NOTE_TO_KEY: Record<string, PublicKey> = {
  'El joven que te recomendamos descubrir': 'note.lynus',
  'La recomendación de la tierra': 'note.luis',
  'El crianza que te recomendamos descubrir': 'note.viuda',
};

export function wineNote(lang: PublicLang, note: string | null | undefined): string {
  if (!note) return '';
  const key = NOTE_TO_KEY[note];
  return key ? t(lang, key) : note;
}

export function allergenName(lang: PublicLang, code: string): string {
  const key = `alg.${code}` as PublicKey;
  return key in M ? t(lang, key) : code;
}

export function sectionLabel(lang: PublicLang, slug: string, fallback: string): string {
  const key = `sec.${slug}` as PublicKey;
  return key in M ? t(lang, key) : fallback;
}

export function wineSectionLabel(lang: PublicLang, section: string): string {
  const key = `wsec.${section}` as PublicKey;
  return key in M ? t(lang, key) : t(lang, 'wsec.otro');
}
